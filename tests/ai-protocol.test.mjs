import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {Client} from '@modelcontextprotocol/sdk/client/index.js';
import {StreamableHTTPClientTransport} from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import {ConfigSchema} from '../server/config.mjs';
import {Service} from '../server/service.mjs';
import {startHttp} from '../server/http.mjs';

test('AI MCP, HTTP and observer SSE share authenticated strict idempotent operations',async t=>{
  const directory=await mkdtemp(join(tmpdir(),'qg-ai-protocol-'));
  let calls=0,controller;
  const service=new Service(ConfigSchema.parse({dataDir:directory,ai:{enabled:true,model:'fixture-model',apiKeyEnv:'TEST_KEY',timeoutMs:3000}}),{
    env:{TEST_KEY:'synthetic-protocol-key'},fetchImpl:async()=>{calls++;return new Response(new ReadableStream({start(c){controller=c;}}),{headers:{'content-type':'text/event-stream'}});}
  });
  const token='ai-protocol-auth-fixture-01234567890123456789',server=await startHttp(service,{port:0,token});
  const origin=`http://127.0.0.1:${server.address().port}`,client=new Client({name:'ai-protocol-test',version:'1'});
  t.after(async()=>{await client.close();await service.close();server.closeAllConnections();await new Promise(resolve=>server.close(resolve));await rm(directory,{recursive:true,force:true});});
  await client.connect(new StreamableHTTPClientTransport(new URL(origin+'/mcp'),{requestInit:{headers:{Authorization:`Bearer ${token}`}}}));
  const headers={Authorization:`Bearer ${token}`,'Content-Type':'application/json'};
  const http=(path,method='GET',body,extra={})=>fetch(origin+path,{method,headers:{...headers,...extra},...(body===undefined?{}:{body:JSON.stringify(body)})});
  const call=(name,args={})=>client.callTool({name,arguments:args});
  const conversation=service.createConversation({idempotencyKey:'protocol'}),request=service.createRequest({conversationId:conversation.id,idempotencyKey:'question',question:'Protocol fixture',cardIds:[]});
  const path=`/api/requests/${request.id}/ai`;
  for(const suffix of ['/api/ai',path,path+'/events'])assert.equal((await fetch(origin+suffix)).status,401);
  assert.equal((await fetch(origin+path+'/start',{method:'POST',headers:{'Content-Type':'application/json'},body:'{}'})).status,401);
  assert.equal((await http(path+'/start','POST',{}, {Origin:'https://evil.example'})).status,403);
  assert.equal((await http('/api/ai?unknown=1')).status,400);
  assert.equal((await http(path+'/start','POST',{requestId:request.id})).status,400);
  for(const name of ['qg_ai_status','qg_start_ai','qg_get_ai','qg_cancel_ai'])assert.equal((await call(name,{requestId:request.id,unexpected:true})).isError,true);
  const tools=(await client.listTools()).tools;
  assert.equal(tools.length,49);assert.equal(tools.find(x=>x.name==='qg_start_ai').annotations.readOnlyHint,false);
  assert.deepEqual((await call('qg_ai_status')).structuredContent,await(await http('/api/ai')).json());
  assert.equal((await call('qg_get_ai',{requestId:request.id})).structuredContent.status,'idle');
  const idleEvents=await(await http(path+'/events')).text();assert.match(idleEvents,/event: snapshot/);assert.match(idleEvents,/"status":"idle"/);assert.equal(calls,0,'read and SSE must never start provider');
  const started=(await call('qg_start_ai',{requestId:request.id})).structuredContent;assert.equal(started.status,'running');
  assert.equal((await http(path+'/start','POST',{})).status,202);assert.equal(calls,1);
  const observe=await http(path+'/events'),reader=observe.body.getReader();const first=new TextDecoder().decode((await reader.read()).value);assert.match(first,/"status":"running"/);
  controller.enqueue(new TextEncoder().encode('event: response.output_text.delta\ndata: {"type":"response.output_text.delta","delta":"Saved partial"}\n\n'));
  await new Promise(resolve=>setTimeout(resolve,20));
  const cancelled=(await call('qg_cancel_ai',{requestId:request.id})).structuredContent;assert.equal(cancelled.status,'cancelled');assert.equal(cancelled.output,'Saved partial');
  let remaining='';for(;;){const next=await reader.read();if(next.done)break;remaining+=new TextDecoder().decode(next.value);}assert.match(remaining,/"status":"cancelled"/);
  assert.deepEqual(await(await http(path+'/cancel','POST',{})).json(),cancelled);
  assert.deepEqual((await call('qg_start_ai',{requestId:request.id})).structuredContent,cancelled);assert.equal(calls,1);
  assert.equal(service.readConversation({conversationId:conversation.id}).messages.length,1);
  assert.equal((await http('/api/requests/request_missing/ai')).status,404);
  assert.equal(JSON.stringify(cancelled).includes('synthetic-protocol-key'),false);
});
